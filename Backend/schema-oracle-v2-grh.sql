-- ----- CANDIDATE_OFFERS (liaison candidat - offre) -----
CREATE TABLE CANDIDATE_OFFERS (
  CANDIDATE_ID NUMBER REFERENCES CANDIDATES(ID) ON DELETE CASCADE,
  OFFER_ID     NUMBER REFERENCES OFFERS(ID) ON DELETE CASCADE,
  APPLIED_AT   DATE DEFAULT SYSDATE,
  STATUS       VARCHAR2(50) DEFAULT 'candidat',
