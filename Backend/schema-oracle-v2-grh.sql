CREATE TABLE ROLES (
  ID   NUMBER PRIMARY KEY,
  NAME VARCHAR2(50) NOT NULL UNIQUE
);
CREATE OR REPLACE TRIGGER ROLES_BI BEFORE INSERT ON ROLES FOR EACH ROW BEGIN IF :NEW.ID IS NULL THEN SELECT ROLES_SEQ.NEXTVAL INTO :NEW.ID FROM DUAL; END IF; END;
