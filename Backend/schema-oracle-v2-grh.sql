-- ----- OFFERS -----
CREATE SEQUENCE OFFERS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE TABLE OFFERS (
  ID          NUMBER PRIMARY KEY,
  TITLE       VARCHAR2(500) NOT NULL,
  DESCRIPTION CLOB,
  SKILLS      CLOB,
  DEADLINE    DATE,
  STATUS      VARCHAR2(50) DEFAULT 'ouverte',
  CREATED_BY  NUMBER REFERENCES USERS(ID),
  CREATED_AT  DATE DEFAULT SYSDATE,
  UPDATED_AT  DATE
);
CREATE OR REPLACE TRIGGER OFFERS_BI BEFORE INSERT ON OFFERS FOR EACH ROW  BEGIN SELECT OFFERS_SEQ.NEXTVAL INTO :NEW.ID FROM DUAL; END;
/
CREATE INDEX IDX_OFFERS_STATUS ON OFFERS(STATUS);

