-- Index pour les requêtes courantes
CREATE INDEX IDX_CANDIDATES_CREATED ON CANDIDATES(CREATED_AT);
CREATE INDEX IDX_CANDIDATES_RETAINED ON CANDIDATES(RETAINED);
